# Helper function to set or replace env var in .env
set_env_var() {
    local key="$1"
    local val="$2"
    if [ ! -f "$ENV_FILE" ]; then
        cp .env.example "$ENV_FILE"
    fi
    if grep -q "^${key}=" "$ENV_FILE"; then
        sed -i "s|^${key}=.*|${key}=${val}|" "$ENV_FILE"
    else
        echo "${key}=${val}" >> "$ENV_FILE"
    fi
}

