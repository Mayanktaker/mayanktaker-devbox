    prompt_key "KILO_API_KEY" "Kilo Code API Key"
    prompt_key "OPENCODE_API_KEY" "OpenCode API Key"
    prompt_key "DEVIN_API_KEY" "Devin AI API Key"
    prompt_key "KIMI_API_KEY" "Kimi Code API Key"
