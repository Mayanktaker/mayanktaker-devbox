    prompt_key "OPENAI_API_KEY" "OpenAI API Key (GPT-4o/Codex)"
    prompt_key "ANTHROPIC_API_KEY" "Anthropic API Key (Claude Code)"
    prompt_key "GEMINI_API_KEY" "Google Gemini / Antigravity API Key"
